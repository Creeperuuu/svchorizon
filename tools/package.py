#!/usr/bin/env python3
"""Create a deterministic source-only .hnmod bundle for Horizon."""
import base64
import hashlib
import json
from pathlib import Path
import shutil
import tomllib
import zipfile

ROOT = Path(__file__).resolve().parents[1]
GAME = "26.3"

# Horizon's native index only accepts .rs and .toml sources under
# mixins/<id>/ (horizon_mods::index::native), so the 4.4 MB RNNoise model
# cannot travel as weights.bin. This rewrites the bundled copy: the model
# becomes a base64 string literal in a generated weights_bytes.rs and the
# bundled weights.rs decodes it at start-up instead of include_bytes!.
WEIGHTS_BYTES_RS = """\
//! Generated by tools/package.py from {bin}: the RNNoise float model as
//! base64, because Horizon's native bundle index only accepts .rs and .toml
//! sources. Do not edit; repackage instead.

pub(crate) const WEIGHTS_B64: &str = "{b64}";

pub(crate) fn decoded() -> &'static [u8] {{
    use std::sync::OnceLock;
    static DECODED: OnceLock<Vec<u8>> = OnceLock::new();
    DECODED
        .get_or_init(|| {{
            const ALPHABET: &[u8; 64] =
                b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
            let mut reverse = [255u8; 256];
            for (index, &byte) in ALPHABET.iter().enumerate() {{
                reverse[byte as usize] = index as u8;
            }}
            let mut out = Vec::with_capacity(WEIGHTS_B64.len() / 4 * 3);
            let mut buffer = 0u32;
            let mut bits = 0u32;
            for &byte in WEIGHTS_B64.as_bytes() {{
                let value = reverse[byte as usize];
                if value == 255 {{
                    continue; // '=' padding and any stray whitespace
                }}
                buffer = (buffer << 6) | value as u32;
                bits += 6;
                if bits >= 8 {{
                    bits -= 8;
                    out.push((buffer >> bits) as u8);
                }}
            }}
            out
        }})
        .as_slice()
}}
"""

INCLUDE_LINE = 'static WEIGHTS_BYTES: &[u8] = include_bytes!("weights.bin");'
PARSE_CALL = "parse(WEIGHTS_BYTES)"
EMBED_LINES = (
    '#[path = "weights_bytes.rs"]\n'
    "mod weights_bytes;\n"
    "fn weights_blob() -> &'static [u8] {\n"
    "    weights_bytes::decoded()\n"
    "}"
)


def embed_weights(source: Path, destination: Path) -> None:
    """Swap the bundled weights.bin for a generated base64 module."""
    bundled_bin = destination / "rnnoise" / "weights.bin"
    bundled_rs = destination / "rnnoise" / "weights.rs"
    if not bundled_bin.is_file() or not bundled_rs.is_file():
        return
    bundled = bundled_rs.read_text()
    if INCLUDE_LINE not in bundled or PARSE_CALL not in bundled:
        raise SystemExit(f"Bundled {bundled_rs} lost its include_bytes! anchor")
    blob = base64.b64encode(bundled_bin.read_bytes()).decode("ascii")
    (destination / "rnnoise" / "weights_bytes.rs").write_text(
        WEIGHTS_BYTES_RS.format(bin="engine/src/rnnoise/weights.bin", b64=blob)
    )
    bundled = bundled.replace(INCLUDE_LINE, EMBED_LINES).replace(
        PARSE_CALL, "parse(weights_blob())"
    )
    if "WEIGHTS_BYTES" in bundled:
        raise SystemExit(f"Bundled {bundled_rs} still references weights.bin bytes")
    bundled_rs.write_text(bundled)
    bundled_bin.unlink()


def prepare_bundle(bundle: Path) -> None:
    source = ROOT / "engine" / "src"
    destination = bundle / "engine" / "src"
    if not (source / "lib.rs").is_file():
        raise SystemExit("Missing vendored engine/src/lib.rs")
    destination.mkdir(parents=True, exist_ok=True)
    if destination.exists():
        shutil.rmtree(destination)
    shutil.copytree(source, destination)
    embed_weights(source, destination)
    tests_source = ROOT / "engine" / "tests"
    if tests_source.is_dir():
        tests_target = bundle / "engine" / "tests"
        if tests_target.exists():
            shutil.rmtree(tests_target)
        shutil.copytree(tests_source, tests_target)
    # The bundle may only contain .rs and .toml files (horizon_mods::index::native
    # rejects anything else), so the BSD license text stays in engine/COPYING at
    # the repository root and travels in the crate's license field instead, and
    # the RNNoise model is embedded as a generated .rs (see embed_weights).

def package():
    compat = json.loads((ROOT / "compatibility.json").read_text())
    manifests = sorted((ROOT / "mixins").glob("*/horizon-mixin.toml"))
    if len(manifests) != 1:
        raise SystemExit("Expected exactly one mixins/<id>/horizon-mixin.toml")
    manifest_path = manifests[0]
    bundle = manifest_path.parent
    mixin = tomllib.loads(manifest_path.read_text())
    mod = mixin["mod"]
    if bundle.name != mod["id"]:
        raise SystemExit("Bundle directory must match the mod id")
    if mixin.get("compatibility", {}).get("horizon_revision") != compat["horizon_revision"]:
        raise SystemExit("Manifest and compatibility.json Horizon revisions differ")
    prepare_bundle(bundle)
    native_manifest = {
        "schema": 1,
        "id": mod["id"],
        "version": mod["version"],
        "game": GAME,
        "horizon": compat["horizon_revision"],
        "mixins": compat["horizon_mixins_revision"],
    }
    files = {
        "horizon-native.json": (json.dumps(native_manifest, indent=2, sort_keys=True) + "\n").encode()
    }
    for path in sorted(bundle.rglob("*")):
        if not path.is_file():
            continue
        if any(part in {".git", "target", "__pycache__"} for part in path.parts):
            continue
        name = path.relative_to(ROOT).as_posix()
        # horizon_mods::index::native rejects any bundle entry that is not a
        # .rs/.toml source: drop strays (COPYING, Cargo.lock, ...) up front.
        if not (name.endswith(".rs") or name.endswith(".toml")):
            print(f"Skipping non-source bundle file: {name}")
            continue
        files[name] = path.read_bytes()
    out = ROOT / "target" / f'{mod["id"]}-{mod["version"]}.hnmod'
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    print(f"Created {out} ({out.stat().st_size} bytes, SHA-256 {digest})")

if __name__ == "__main__":
    package()

#!/usr/bin/env python3
"""Generate the RNNoise Rust table module (half window + DCT) from
xiph/rnnoise's rnnoise_tables.c, so the denoiser uses the exact constants of
the upstream build instead of regenerating them."""
from pathlib import Path
import re
import sys

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    "/home/z/my-project/workspace/rnnoise-classic/src/rnnoise_tables.c")
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(
    "/home/z/my-project/workspace/svchorizon/engine/src/rnnoise/tables.rs")


def array(name):
    body = re.search(
        rf"const float {name}\[\]\s*=\s*\{{(.*?)\}};", SRC.read_text(), re.DOTALL
    ).group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.DOTALL)
    values = [p.strip() for p in body.split(",") if p.strip()]
    return [float(v.rstrip("f")) for v in values]


def fmt(values, per_line):
    lines = []
    for start in range(0, len(values), per_line):
        chunk = ", ".join(fmt_float(v) for v in values[start:start + per_line])
        lines.append(f"    {chunk},")
    return "\n".join(lines)


def fmt_float(value):
    text = f"{value:.9g}"
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


half_window = array("rnn_half_window")
dct_table = array("rnn_dct_table")
assert len(half_window) == 480, len(half_window)
assert len(dct_table) == 32 * 32, len(dct_table)

OUT.write_text(f"""// Generated by scripts/extract_rnnoise_tables.py from xiph/rnnoise's
// rnnoise_tables.c (commit 372f7b4b76cde4ca1ec4605353dd17898a99de38, the
// revision Simple Voice Chat's denoiser library builds). Do not edit.
#![allow(clippy::excessive_precision)]

/// The analysis/synthesis window's half, `FRAME_SIZE` entries; applied
/// symmetrically like upstream `apply_window`.
pub const HALF_WINDOW: [f32; 480] = [
{fmt(half_window, 6)}
];

/// The band DCT, row-major `[input_band][output_feature]`, used as
/// `sum += in[j] * DCT_TABLE[j * 32 + i]`.
pub const DCT_TABLE: [f32; 1024] = [
{fmt(dct_table, 6)}
];
""")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")

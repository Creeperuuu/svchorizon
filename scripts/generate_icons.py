#!/usr/bin/env python3
"""Convert Simple Voice Chat's HUD icon textures into palette-encoded Rust
constants for the mod's runtime module. Sources: the official client's
assets (16x16), so the icons look exactly like the official mod's."""
from pathlib import Path
import sys
from PIL import Image

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    "/home/z/my-project/workspace/svc-2.6x-1.21.11/common-client/src/main/resources/assets/voicechat/textures/icons")

ICONS = [
    "microphone", "microphone_whisper", "microphone_off",
    "speaker", "speaker_whisper", "speaker_off",
    "disconnected", "group", "lock", "adjust_volumes",
    "record_button", "speaker_button", "microphone_button", "hide_button",
]


def emit(name, path):
    image = Image.open(path).convert("RGBA")
    width, height = image.size
    assert (width, height) in ((16, 16), (32, 32)), (name, width, height)
    pixels = list(image.getdata())
    palette = []
    indices = []
    for rgba in pixels:
        if rgba[3] == 0:
            indices.append(0)
            if not palette:
                palette.append((0, 0, 0, 0))
            continue
        if rgba not in palette:
            palette.append(rgba)
        indices.append(palette.index(rgba))
    assert len(palette) <= 256, (name, len(palette))
    argb = [((r << 24) | (g << 16) | (b << 8) | a)
            for (r, g, b, a) in palette]
    # Reserve index 0 as transparent.
    argb[0] = 0
    const = name.upper()
    lines = [f"/// `textures/icons/{name}.png` ({width}x{height}), palette-encoded."]
    lines.append(f"pub(crate) const {const}: Icon = Icon {{")
    lines.append(f"    size: {width},")
    lines.append("    palette: &[")
    for start in range(0, len(argb), 4):
        row = ", ".join(f"0x{value:08X}" for value in argb[start:start + 4])
        lines.append(f"        {row},")
    lines.append("    ],")
    lines.append("    indices: &[")
    for start in range(0, len(indices), 16):
        row = ", ".join(f"0x{value:X}" for value in indices[start:start + 16])
        lines.append(f"        {row},")
    lines.append("    ],\n};")
    return "\n".join(lines)


parts = [
    "// Generated by scripts/generate_icons.py from Simple Voice Chat's",
    "// textures/icons (the official client's HUD art, CC0-BSD-3 licensed",
    "// upstream assets). Do not edit; regenerate instead.",
    "",
    "/// A palette-encoded icon: index 0 is transparent.",
    "pub(crate) struct Icon {",
    "    pub(crate) size: u32,",
    "    pub(crate) palette: &'static [u32],",
    "    pub(crate) indices: &'static [u8],",
    "}",
    "",
]
for icon in ICONS:
    parts.append(emit(icon, SRC / f"{icon}.png"))
    parts.append("")
RUNTIME = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(
    "/home/z/my-project/workspace/svchorizon/mixins/svchorizon/runtime.rs")
BEGIN = "// ICONS-BEGIN (generated by scripts/generate_icons.py)"
END = "// ICONS-END"
body = "\n".join(parts)
# The wrapper module already defines `struct Icon`; keep only the constants.
first_const = body.index("/// `textures/icons/")
body = body[first_const:]
runtime = RUNTIME.read_text()
if BEGIN in runtime and END in runtime:
    before = runtime[:runtime.index(BEGIN) + len(BEGIN)]
    after = runtime[runtime.index(END):]
    RUNTIME.write_text(f"{before}\n{body}\n{after}")
    print(f"spliced {len(ICONS)} icons into {RUNTIME}")
else:
    OUT = Path("icons_gen.rs")
    OUT.write_text(body)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(ICONS)} icons); "
          "add ICONS-BEGIN/ICONS-END markers to splice it into runtime.rs")
